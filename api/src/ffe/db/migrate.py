"""Programmatic Alembic: same scripts and configuration as the `alembic` CLI (api/alembic.ini)."""

from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Connection, Engine

ALEMBIC_DIR = Path(__file__).resolve().parents[3] / "alembic"


def alembic_config(connection: Connection | None = None) -> Config:
    config = Config()
    config.set_main_option("script_location", str(ALEMBIC_DIR))
    if connection is not None:
        config.attributes["connection"] = connection
    return config


def head_revision() -> str:
    head = ScriptDirectory.from_config(alembic_config()).get_current_head()
    if head is None:
        raise RuntimeError("Aucune migration Alembic trouvée.")
    return head


def revision_chain() -> list[str]:
    """Revisions from base to head, in application order."""
    script = ScriptDirectory.from_config(alembic_config())
    return [rev.revision for rev in reversed(list(script.walk_revisions()))]


def current_revision(engine: Engine) -> str | None:
    with engine.connect() as conn:
        return MigrationContext.configure(conn).get_current_revision()


def has_pending(engine: Engine) -> bool:
    return current_revision(engine) != head_revision()


def upgrade_head(engine: Engine) -> None:
    with engine.begin() as conn:
        command.upgrade(alembic_config(conn), "head")


def downgrade_base(engine: Engine) -> None:
    with engine.begin() as conn:
        command.downgrade(alembic_config(conn), "base")


def schema_drift(engine: Engine) -> bool:
    """True when the models and the database schema differ (same test as `alembic check`)."""
    try:
        check(engine)
    except AutogenerateDiffsDetected:
        return True
    return False


def check(engine: Engine) -> None:
    """Raises `alembic.util.exc.AutogenerateDiffsDetected` when models and migrations differ."""
    with engine.connect() as conn:
        command.check(alembic_config(conn))
